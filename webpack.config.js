/*
 * The default @wordpress/scripts build (every src/blocks/<name>/block.json becomes a block) plus the front end, split
 * so a page loads only what it uses (marccent-blocks.php picks the files per page):
 * - runtime/index: the script (React root, islands), only on pages with something interactive.
 * - styles/core: the theme's styles without the design styles and without Font Awesome's icon rules.
 * - designs/<id>: one design style each (marccent-theme's styles/designs/<id>.css); designs/all: every one, for the
 *   editor and for sites whose visitors switch styles (the theme button).
 * - styles/icons: every Font Awesome icon, for the editor (a page gets only its own: build/icons.php).
 * - icons.php: every icon's rule by name and the icons the scripts can render; theme-defaults.json: the package's
 *   theme defaults, so PHP can paint the starting colors; marccent-theme.json: the package's version.
 *
 * marccent-theme's components import no router (their links are plain <a>s unless a host hands them one), so they
 * build as they are. The site's starting theme reaches the package as window.marccentDefaults (printed by
 * inc/assets.php from the marccent_defaults option), which its lib/defaults.js merges over its own. marccent-theme is
 * a release (package.json: github:…#v<version>) and ships JSX source, so babel compiles it too, though it's in
 * node_modules.
 */
const fs = require( 'fs' );
const path = require( 'path' );
const webpack = require( 'webpack' );
const defaultConfig = require( '@wordpress/scripts/config/webpack.config' );
const fa = require( './tools/font-awesome' );

const PACKAGE = path.dirname( require.resolve( 'marccent-theme/package.json' ) );
const FA_BASE = fa.base();

const designs = Object.fromEntries( fs.readdirSync( path.join( PACKAGE, 'styles/designs' ) )
	.filter( ( f ) => f.endsWith( '.css' ) )
	.map( ( f ) => [ `designs/${ path.basename( f, '.css' ) }`, path.join( PACKAGE, 'styles/designs', f ) ] ) );

// build/icons.php and build/theme-defaults.json, from the package; the icons the front-end scripts can render are
// read from the compiled chunks (not the blocks' editor scripts, not p5).
class FrontEndData {
	apply( compiler ) {
		compiler.hooks.thisCompilation.tap( 'FrontEndData', ( compilation ) => {
			compilation.hooks.processAssets.tap( { name: 'FrontEndData', stage: webpack.Compilation.PROCESS_ASSETS_STAGE_REPORT }, ( assets ) => {
				const all = fa.icons();
				const code = Object.keys( assets )
					.filter( ( name ) => /\.js(\?|$)/.test( name ) && ! name.startsWith( 'blocks/' ) && assets[ name ].size() < 300000 )
					.map( ( name ) => assets[ name ].source().toString() ).join( '\n' );
				const php = `<?php // GENERATED by webpack.config.js: Font Awesome's icon rules by name, and the icons the scripts render.\n`
					+ `return array( 'all' => ${ phpArray( all ) }, 'runtime' => ${ phpArray( fa.used( code, all ) ) } );\n`;
				compilation.emitAsset( 'icons.php', new webpack.sources.RawSource( php ) );
				compilation.emitAsset( 'theme-defaults.json', new webpack.sources.RawSource( fs.readFileSync( path.join( PACKAGE, 'lib/theme.defaults.json' ) ) ) );
				const { version } = JSON.parse( fs.readFileSync( path.join( PACKAGE, 'package.json' ), 'utf8' ) );
				compilation.emitAsset( 'marccent-theme.json', new webpack.sources.RawSource( JSON.stringify( { version } ) ) );
			} );
		} );
	}
}
// postcss-loader looks for its config from each stylesheet's folder up, so the theme's files (outside this plugin)
// would get none: every stylesheet uses this plugin's postcss.config.js.
const POSTCSS = path.resolve( __dirname, 'postcss.config.js' );
const withPostcss = ( rule ) => ( {
	...rule,
	use: Array.isArray( rule.use ) ? rule.use.map( ( u ) => u.loader?.includes( 'postcss-loader' )
		? { ...u, options: { ...u.options, postcssOptions: { config: POSTCSS } } }
		: u ) : rule.use,
} );

// The JS rules leave node_modules alone, but marccent-theme there is JSX source: babel compiles it too.
const OUR_SOURCE = /node_modules\/(?!marccent-theme\/)/;
const withTheme = ( rule ) => ( String( rule.exclude ) === '/node_modules/' ? { ...rule, exclude: OUR_SOURCE } : rule );

const phpString = ( s ) => `'${ String( s ).replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;
const phpArray = ( v ) => Array.isArray( v )
	? `array( ${ v.map( phpString ).join( ', ' ) } )`
	: `array( ${ Object.entries( v ).map( ( [ k, x ] ) => `${ phpString( k ) } => ${ phpString( x ) }` ).join( ', ' ) } )`;

module.exports = {
	...defaultConfig,
	entry: {
		...defaultConfig.entry(),
		'runtime/index': './src/runtime/index.js',
		'styles/core': './src/runtime/styles.js',
		'styles/icons': path.join( fa.DIR, 'css/all.css' ),
		'designs/all': path.join( PACKAGE, 'styles/designs.css' ),
		...designs,
	},
	module: { ...defaultConfig.module, rules: defaultConfig.module.rules.map( withPostcss ).map( withTheme ) },
	resolve: {
		...defaultConfig.resolve,
		alias: {
			...defaultConfig.resolve.alias,
			// The theme brings all of Font Awesome in one file (styles/fontawesome.css); here it's the base, and each
			// page gets its own icons.
			[ path.join( PACKAGE, 'styles/fontawesome.css' ) ]: FA_BASE,
		},
	},
	plugins: [
		...defaultConfig.plugins,
		// A component's own stylesheet (button.js imports styles/components/button.css) is already in styles/core:
		// left out, or each island's chunk would load a second copy.
		new webpack.NormalModuleReplacementPlugin( /styles\/components\/[^/]+\.css$/, ( res ) => {
			if ( res.context.startsWith( path.join( PACKAGE, 'components' ) ) ) {
				res.request = path.resolve( __dirname, 'src/shims/empty.js' );
			}
		} ),
		new FrontEndData(),
	],
};
