/*
 * Font Awesome, split so a page only gets the icons it shows. Its stylesheets are mostly one rule per icon
 * (.fa-snowflake { --fa: "\f2dc"; }), about 2,500 of them; the rest is the base (.fa-solid::before { content:
 * var(--fa) }, sizes, animations) and each family's @font-face.
 *
 * - base(): writes src/generated/fa-base.css: the families' @font-face and the base, without the icon rules. The
 *   theme's styles/fontawesome.css resolves to it (webpack.config.js).
 * - icons(): every icon's rule body by name, for marccent-blocks.php to print only the page's (build/icons.php).
 * - used( code, all ): the icon names a compiled script mentions as strings ("bars-staggered", "xmark"): the icons
 *   the islands' components can render that aren't in the server's markup.
 */
const fs = require( 'fs' );
const path = require( 'path' );
const postcss = require( 'postcss' );

const DIR = path.dirname( require.resolve( '@fortawesome/fontawesome-free/package.json', { paths: [ path.dirname( require.resolve( 'marccent-theme/package.json' ) ) ] } ) );
const GENERATED = path.resolve( __dirname, '../src/generated' );

// An icon rule: only .fa-<name> selectors (an icon and its aliases) and a single --fa.
const isIcon = ( rule ) => rule.type === 'rule' && rule.selectors.every( ( s ) => /^\.fa-[a-z0-9-]+$/.test( s ) ) &&
	rule.nodes.length === 1 && rule.nodes[ 0 ].prop === '--fa';

// The base and every icon live in fontawesome.css, the brand icons in brands.css beside the brands' @font-face.
const FILES = [ 'fontawesome', 'solid', 'regular', 'brands' ];
const tree = ( name ) => postcss.parse( fs.readFileSync( path.join( DIR, `css/${ name }.css` ), 'utf8' ) );

const base = () => {
	const webfonts = path.relative( GENERATED, path.join( DIR, 'webfonts' ) );
	const css = FILES.map( ( name ) => {
		const file = tree( name );
		file.each( ( node ) => {
			if ( isIcon( node ) ) {
				node.remove();
			}
		} );
		return file.toString().replaceAll( '../webfonts', webfonts );
	} );
	fs.mkdirSync( GENERATED, { recursive: true } );
	const file = path.join( GENERATED, 'fa-base.css' );
	fs.writeFileSync( file, `/* GENERATED by tools/font-awesome.js: Font Awesome without its icon rules. */\n${ css.join( '\n' ) }\n` );
	return file;
};

const icons = () => {
	const out = {};
	FILES.forEach( ( name ) => tree( name ).each( ( node ) => {
		if ( isIcon( node ) ) {
			node.selectors.forEach( ( s ) => ( out[ s.slice( 4 ) ] = node.nodes[ 0 ].value ) );
		}
	} ) );
	return out;
};

// A bare name needs 3 letters at least: shorter strings ("d", "th": date formats) are rarely icons.
const used = ( code, all ) => [ ...new Set( [ ...code.matchAll( /["'`](fa-)?([a-z0-9-]+)["'`]/g ) ]
	.filter( ( m ) => m[ 1 ] || m[ 2 ].length > 2 ).map( ( m ) => m[ 2 ] ) ) ].filter( ( n ) => n in all );

module.exports = { DIR, base, icons, used };
